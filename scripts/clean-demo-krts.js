// ── file IO ────────────────────────────────────────────────────────────
const isKrtFile = (f) => /\.(csv|xlsx)$/i.test(f) && !/-DS\d+\.xlsx$/i.test(f);

const colIndex = (header, name) =>
  header.findIndex((h) => String(h || '').replace(/^\uFEFF/, '').trim().toUpperCase() === name);

/**
 * Read a CSV without changing what it is.
 *
 * One file in this corpus is not valid UTF-8, and decoding it as UTF-8 and
 * writing it back would replace those bytes with U+FFFD — silently corrupting
 * rows this script was never asked to touch. So the encoding is detected and
 * carried through to the write, and the delimiter is taken from the parse
 * rather than assumed.
 */
function readCsv(file) {
  const buf = fs.readFileSync(file);
  let encoding = 'utf8';
  try {
    new TextDecoder('utf-8', { fatal: true }).decode(buf);
  } catch {
    encoding = 'latin1';
  }
  const text = buf.toString(encoding);
  const parsed = Papa.parse(text, { header: false, skipEmptyLines: false });
  return { rows: parsed.data, encoding, delimiter: parsed.meta?.delimiter || ',', newline: text.includes('\r\n') ? '\r\n' : '\n' };
}

async function readXlsx(file) {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(file);
  return { kind: 'xlsx', wb, ws: wb.worksheets[0] };
}

/** Every change made, for the report. */
const changes = [];

async function processFile(file) {
  const full = path.join(DIR, file);
  const decisions = DECISIONS.filter((d) => d.file === file);
  let touched = 0;

  if (file.toLowerCase().endsWith('.csv')) {
    const { rows, encoding, delimiter, newline } = readCsv(full);
    if (!rows.length) return;
    const header = rows[0];
    const idOf = (name) => colIndex(header, name);
    const get = (row, name) => {
      const i = idOf(name);
      return i === -1 ? '' : String(row[i] ?? '').trim();
    };
    const idIdx = idOf('IDENTIFIER');

    for (let r = 1; r < rows.length; r++) {
      const row = rows[r];
      if (!row || row.every((c) => String(c ?? '').trim() === '')) continue;

      if (idIdx !== -1) {
        const v = String(row[idIdx] ?? '').trim();
        if (v === '' || isNA(v)) {
          row[idIdx] = NO_IDENTIFIER;
          changes.push([file, r + 1, 'IDENTIFIER', v || '(empty)', NO_IDENTIFIER, 'no identifier for this row']);
          touched++;
        }
      }
      for (const d of decisions) {
        const i = idOf(d.column);
        if (i === -1) continue;
        const v = String(row[i] ?? '').trim();
        if (v !== d.from) continue;
        if (d.onlyWhen && !d.onlyWhen(row, get)) continue;
        row[i] = d.to;
        changes.push([file, r + 1, d.column, v || '(empty)', d.to, d.why]);
        touched++;
      }
    }

    if (touched && !DRY) {
      // Guarded: a second run must not overwrite the pristine backup.
      if (!fs.existsSync(full + '.bak2')) fs.copyFileSync(full, full + '.bak2');
      fs.writeFileSync(full, Papa.unparse(rows, { delimiter, newline }), encoding);
    }
    return;
  }

  const { wb, ws } = await readXlsx(full);
  const header = ws.getRow(1).values.slice(1).map((v) => String(v ?? ''));
  const idOf = (name) => { const i = colIndex(header, name); return i === -1 ? -1 : i + 1; };
  const get = (row, name) => {
    const i = idOf(name);
    return i === -1 ? '' : String(row.getCell(i).value ?? '').trim();
  };
  const idIdx = idOf('IDENTIFIER');

  ws.eachRow((row, n) => {
    if (n === 1) return;
    const empty = header.every((_, j) => String(row.getCell(j + 1).value ?? '').trim() === '');
    if (empty) return;

    if (idIdx !== -1) {
      const v = String(row.getCell(idIdx).value ?? '').trim();
      if (v === '' || isNA(v)) {
        row.getCell(idIdx).value = NO_IDENTIFIER;
        changes.push([file, n, 'IDENTIFIER', v || '(empty)', NO_IDENTIFIER, 'no identifier for this row']);
        touched++;
      }
    }
    for (const d of decisions) {
      const i = idOf(d.column);
      if (i === -1) continue;
      const v = String(row.getCell(i).value ?? '').trim();
      if (v !== d.from) continue;
      if (d.onlyWhen && !d.onlyWhen(row, get)) continue;
      row.getCell(i).value = d.to;
      changes.push([file, n, d.column, v || '(empty)', d.to, d.why]);
      touched++;
    }
  });

  if (touched && !DRY) {
    // Guarded: a second run must not overwrite the pristine backup.
    if (!fs.existsSync(full + '.bak2')) fs.copyFileSync(full, full + '.bak2');
    await wb.xlsx.writeFile(full);
  }
}

(async () => {
  const files = fs.readdirSync(DIR).filter(isKrtFile).sort();
  for (const f of files) await processFile(f);

  const byFile = {};
  for (const c of changes) byFile[c[0]] = (byFile[c[0]] || 0) + 1;
  for (const [f, n] of Object.entries(byFile)) console.log(`${f} — ${n} cell(s)`);
  console.log(`\n${changes.length} cell(s) ${DRY ? 'would change' : 'changed'} across ${Object.keys(byFile).length} file(s)`);

  const notIdentifier = changes.filter((c) => c[2] !== 'IDENTIFIER');
  if (notIdentifier.length) {
    console.log('\nJudgement calls (everything that is not an identifier placeholder):');
    for (const [f, r, col, from, to, why] of notIdentifier) {
      console.log(`  ${f} r${r} ${col}: ${JSON.stringify(from)} → ${JSON.stringify(to)}  (${why})`);
    }
  }
})();
